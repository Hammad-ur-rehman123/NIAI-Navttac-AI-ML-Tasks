# Task 21: List data type in Python

fruits = ["apple", "banana", "cherry"]
print("Original:", fruits)

# Indexing and slicing
print(fruits[0], fruits[-1])
numbers = [10, 20, 30, 40, 50, 60]
print(numbers[1:4], numbers[::-1])

# Adding items
fruits.append("mango")
fruits.insert(1, "orange")
fruits.extend(["kiwi", "grapes"])
print("After adding:", fruits)

# Removing items
fruits.remove("banana")
popped = fruits.pop()
del fruits[0]
print("After removing:", fruits, "| popped:", popped)

# Sorting and reversing
nums = [5, 2, 9, 1, 7]
nums.sort()
print("Sorted:", nums)
nums.sort(reverse=True)
print("Reverse sorted:", nums)
nums.reverse()
print("Reversed:", nums)

# Useful methods
data = [1, 2, 2, 3, 3, 3]
print("Count of 3:", data.count(3))
print("Index of 2:", data.index(2))
print("Length:", len(data), "Sum:", sum(data), "Max:", max(data))

# Copying
copy_list = data.copy()
copy_list.append(99)
print(data, copy_list)

# Nested list
matrix = [[1, 2, 3], [4, 5, 6]]
print(matrix[1][2])

# Looping and list comprehension
for i, f in enumerate(["a", "b", "c"]):
    print(i, f)
squares = [n ** 2 for n in range(1, 6)]
print("Squares:", squares)