# Task 22: Tuple data type in Python

t = (10, 20, 30, 40, 20)
print("Tuple:", t)

# Indexing and slicing
print(t[0], t[-1], t[1:4])

# Tuples are immutable
try:
    t[0] = 99
except TypeError as e:
    print("Error:", e)

# Single element tuple needs a comma
single = (5,)
print(type(single), type((5)))


# Concatenation and repetition
a = (1, 2)
b = (3, 4)
print(a + b, a * 3)

# Nested tuple
nested = ((1, 2), (3, 4))
print(nested[1][0])

# Looping
for item in t:
    print(item, end=" ")
print()

# Membership
print(30 in t, 99 in t)