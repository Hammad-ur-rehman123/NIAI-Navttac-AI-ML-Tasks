# Task 25: Dictionary data type in Python

student = {"name": "Ali", "age": 22, "city": "Lahore"}
print(student)

# Accessing values
print(student["name"])
print(student.get("age"))
print(student.get("grade", "Not found"))

# Adding and updating
student["grade"] = "A"
student["age"] = 23
student.update({"city": "Karachi", "course": "AI"})
print(student)

# Removing items
student.pop("grade")
del student["course"]
last = student.popitem()
print("Popped:", last, "| Now:", student)

# Keys, values and items
d = {"a": 1, "b": 2, "c": 3}
print(list(d.keys()), list(d.values()), list(d.items()))

# Looping
for key, value in d.items():
    print(key, "->", value)

# Membership
print("a" in d, "z" in d)

# Dictionary comprehension
squares = {n: n ** 2 for n in range(1, 6)}
print(squares)

# Nested dictionary
students = {
    "s1": {"name": "Ali", "marks": 85},
    "s2": {"name": "Sara", "marks": 92},
}
print(students["s2"]["name"], students["s2"]["marks"])

# Merging
x = {"a": 1}
y = {"b": 2}
print({**x, **y})

# Counting characters
text = "banana"
count = {}
for ch in text:
    count[ch] = count.get(ch, 0) + 1
print(count)

# Sorting by value
print(sorted(d.items(), key=lambda item: item[1], reverse=True))