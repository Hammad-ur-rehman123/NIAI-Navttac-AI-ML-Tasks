# Task 23: String data type in Python

s = "Hello, World"
print(s, len(s))

# Indexing and slicing
print(s[0], s[-1], s[7:13], s[::-1])

# Case methods
print(s.upper(), s.lower(), s.title(), s.swapcase(), s.capitalize())

# Search and replace
print(s.find("Python"), s.count("o"), s.replace("World", "AI"))
print(s.startswith("Hello"), s.endswith("World"))

# Split and join
words = s.split()
print(words)
print("-".join(words))

# Strip whitespace
messy = "   spaces around   "
print(f"[{messy.strip()}]", f"[{messy.lstrip()}]", f"[{messy.rstrip()}]")


# Formatting
name, age = "Ali", 22
print("Name: {}, Age: {}".format(name, age))
print(f"Name: {name}, Age: {age}")
print("Pi is %.2f" % 3.14159)


# Strings are immutable
try:
    s[0] = "J"
except TypeError as e:
    print("Error:", e)