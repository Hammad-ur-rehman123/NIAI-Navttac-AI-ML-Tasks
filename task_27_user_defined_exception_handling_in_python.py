# Task 27: User defined exception handling in Python

# 1. Simple custom exception
class NegativeNumberError(Exception):
    """Raised when a negative number is given."""
    pass

def square_root(n):
    if n < 0:
        raise NegativeNumberError("Negative numbers are not allowed")
    return n ** 0.5

try:
    print(square_root(16))
    print(square_root(-4))
except NegativeNumberError as e:
    print("Error:", e)


# 2. Custom exception with extra data
class InsufficientBalanceError(Exception):
    def __init__(self, balance, amount):
        self.balance = balance
        self.amount = amount
        super().__init__(f"Balance {balance} is less than withdrawal {amount}")

class BankAccount:
    def __init__(self, balance):
        self.balance = balance

    def withdraw(self, amount):
        if amount > self.balance:
            raise InsufficientBalanceError(self.balance, amount)
        self.balance -= amount
        return self.balance

account = BankAccount(1000)
try:
    print(account.withdraw(300))
    print(account.withdraw(900))
except InsufficientBalanceError as e:
    print("Error:", e)
    print("Short by:", e.amount - e.balance)


# 3. Exception hierarchy
class AppError(Exception):
    """Base class for app errors."""

class InvalidAgeError(AppError):
    pass

class InvalidNameError(AppError):
    pass

def register(name, age):
    if not name:
        raise InvalidNameError("Name cannot be empty")
    if not 0 < age < 120:
        raise InvalidAgeError("Age must be between 1 and 119")
    return f"{name} registered"

for name, age in [("Ali", 25), ("", 20), ("Sara", 200)]:
    try:
        print(register(name, age))
    except InvalidNameError as e:
        print("Name problem:", e)
    except AppError as e:
        print("App problem:", e)