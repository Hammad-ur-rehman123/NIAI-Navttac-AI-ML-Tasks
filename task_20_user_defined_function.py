# Task 20: User defined functions in Python

# 1. Simple function
def greet(name):
    return f"Hello, {name}!"

print(greet("Ali"))

# 2. Function with default argument
def power(base, exponent=2):
    return base ** exponent

print(power(5))
print(power(2, 5))

# 3. Function with multiple return values

def min_max(numbers):
    return min(numbers), max(numbers)

lo, hi = min_max([4, 9, 1, 7])
print("Min:", lo, "Max:", hi)

# 4. Function with *args and **kwargs
def total(*args):
    return sum(args)

def show_info(**kwargs):
    for key, value in kwargs.items():
        print(f"{key}: {value}")

print(total(10,2,4,6,8,9))
show_info(name="Sara", age=34, city="Lahore")

# 5. Variable scope
x = 10

def scope_demo():
    x = 5
    print("Inside function x =", x)

scope_demo()
print("Outside function x =", x)

# 6. Lambda, map and filter
square = lambda n: n * n
print(square(6))

nums = [1, 2, 3, 4, 5, 6]
print(list(map(lambda n: n * 2, nums)))
print(list(filter(lambda n: n % 2 == 0, nums)))

# 7. Nested (inner) function
def outer(a):
    def inner(b):
        return a + b
    return inner

add_five = outer(7)
print(add_five(3))