# Task 26: Exception Handling

# 1. try / except method
try:
    print(10 / 0)
except ZeroDivisionError:
    print("Cannot divide by zero")

# 2. Handling a specific error type
try:
    number = int("abc")
except ValueError:
    print("This is not a valid number")

# 3. Showing the error message
try:
    numbers = [1, 2, 3]
    print(numbers[10])
except IndexError as e:
    print("Error:", e)

# 4. else and finally
try:
    x = int("5")
except ValueError:
    print("Invalid value")
else:
    print("No error occurred, x =", x)
finally:
    print("This always runs")

# 5. raise: raising an error ourselves
age = -5
try:
    if age < 0:
        raise ValueError("Age cannot be negative")
except ValueError as e:
    print("Error:", e)