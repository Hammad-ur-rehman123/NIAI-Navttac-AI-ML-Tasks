# Task 24: Set data type in Python

s = {1, 2, 3, 3, 2, 1}
print("Duplicates removed:", s)

# Creating sets
empty = set()
from_list = set([4, 5, 5, 6])
print(empty, from_list)

# Adding and removing
s.add(10)
s.update([20, 30])
print("After add/update:", s)
s.remove(10)
s.discard(999)
popped = s.pop()
print("After removing:", s, "| popped:", popped)

# Membership and length
print(3 in a, len(a))

# Removing duplicates from a list
nums = [1, 2, 2, 3, 3, 3, 4]
print(list(set(nums)))

# Set comprehension
print({x ** 2 for x in range(5)})